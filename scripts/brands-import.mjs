// Fits each product mark in brands/source/ onto the icon grid and writes src/brands.mjs.
// The marks are our own logos, so they are not redrawn: their paths are scaled
// uniformly into the 2px padding (20 units across, centred), with an optical size
// per mark, and rounded to two decimals. Needs Playwright (for the bounding boxes).
//   node scripts/brands-import.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "brands", "source");

// title, and how much of the 20-unit live area the mark's longer side fills.
// Round and diamond marks read larger than square ones, so they get a little less.
export const BRAND_META = {
  onceUI: { title: "Once UI", size: 19 },
  aveiro: { title: "Aveiro", size: 19 },
  chirio: { title: "Chirio", size: 20 },
  tavilio: { title: "Tavilio", size: 20 },
  sigilio: { title: "Sigilio", size: 19.5 },
  stack: { title: "Stack", size: 19 },
  frametic: { title: "Frametic", size: 19.5 },
  dopler: { title: "Dopler", size: 20 },
};

const r2 = (n) => +n.toFixed(2);
const ARGS = { M: 2, L: 2, H: 1, V: 1, C: 6, S: 4, Q: 4, T: 2, A: 7, Z: 0 };

/** Scales and moves a path: absolute points get k*p + o, relative ones k*p; arc radii scale, flags stay. */
export function transformPath(d, k, ox, oy) {
  const tokens = d.match(/[a-zA-Z]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?/g);
  let out = "", i = 0, cmd = "";
  while (i < tokens.length) {
    if (/[a-zA-Z]/.test(tokens[i])) cmd = tokens[i++];
    else if (cmd === "M") cmd = "L"; else if (cmd === "m") cmd = "l";
    const C = cmd.toUpperCase(), rel = cmd !== C, n = ARGS[C];
    const a = tokens.slice(i, i + n).map(Number); i += n;
    const X = (v) => r2(rel ? v * k : v * k + ox), Y = (v) => r2(rel ? v * k : v * k + oy);
    let v;
    if (C === "Z") v = [];
    else if (C === "H") v = [X(a[0])];
    else if (C === "V") v = [Y(a[0])];
    else if (C === "A") v = [r2(a[0] * k), r2(a[1] * k), a[2], a[3], a[4], X(a[5]), Y(a[6])];
    else v = a.map((p, j) => (j % 2 ? Y(p) : X(p)));
    out += cmd + v.join(" ");
  }
  return out.replace(/ -/g, "-");
}

// A path's evenodd fill rule is kept, so marks with holes stay open.
const marks = fs.readdirSync(SRC).filter((f) => f.endsWith(".svg")).map((f) => {
  const name = f.replace(/\.svg$/, "");
  const tags = [...fs.readFileSync(path.join(SRC, f), "utf8").matchAll(/<path\b[^>]*>/g)].map((m) => m[0]);
  const parts = [...new Map(tags.map((t) => [t.match(/\sd="([^"]+)"/)[1], /fill-rule="evenodd"/.test(t)])).entries()];
  return { name, ds: parts.map(([d]) => d), evenodd: parts.map(([, e]) => e) };
});

const { chromium } = createRequire(import.meta.url)("playwright");
const browser = await chromium.launch();
const page = await browser.newPage();
const boxes = await page.evaluate((marks) => marks.map(({ ds }) => {
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  document.body.appendChild(svg);
  const g = document.createElementNS("http://www.w3.org/2000/svg", "g");
  svg.appendChild(g);
  for (const d of ds) { const p = document.createElementNS("http://www.w3.org/2000/svg", "path"); p.setAttribute("d", d); g.appendChild(p); }
  const b = g.getBBox();
  return { x: b.x, y: b.y, w: b.width, h: b.height };
}), marks);
await browser.close();

const BRANDS = {};
marks.forEach(({ name, ds, evenodd }, j) => {
  const b = boxes[j], size = BRAND_META[name]?.size ?? 20, k = size / Math.max(b.w, b.h);
  const ox = 12 - (b.x + b.w / 2) * k, oy = 12 - (b.y + b.h / 2) * k;
  BRANDS[name] = ds.map((d, i) => (evenodd[i] ? { d: transformPath(d, k, ox, oy), evenodd: true } : transformPath(d, k, ox, oy)));
});

fs.writeFileSync(path.join(ROOT, "src", "brands-paths.mjs"),
  `// Generated by scripts/brands-import.mjs from brands/source/. Do not edit by hand.\nexport const BRAND_PATHS = ${JSON.stringify(BRANDS, null, 2)};\n`);
console.log("imported", Object.keys(BRANDS).join(", "));
